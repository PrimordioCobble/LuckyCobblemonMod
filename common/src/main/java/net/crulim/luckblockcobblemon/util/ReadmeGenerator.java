package net.crulim.luckblockcobblemon.util;

import net.crulim.luckblockcobblemon.config.LuckyBlockConfigManager;

import java.io.IOException;
import java.io.OutputStreamWriter;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

public class ReadmeGenerator {

    public static void generateReadmeIfMissing() {
        LuckyBlockConfigManager.ensureDirectories();

        Path readme = LuckyBlockConfigManager.rootDir().resolve("README.txt");
        if (Files.exists(readme) && isCurrent(readme)) {
            return;
        }

        String content = """
                ==============================
                LUCKY BLOCK COBBLEMON CONFIGS
                ==============================

                Official config folder:

                config/luckyblockcobblemon/
                ├── settings.json
                ├── tiers.json
                └── pools/
                    ├── default.json
                    ├── legendary.json
                    └── themed/
                        ├── fire.json
                        ├── water.json
                        ├── grass.json
                        ├── ground.json
                        ├── fly.json
                        ├── steel.json
                        ├── eletric.json
                        └── fairy.json

                IMPORTANT:

                The files generated by the mod are GLOBAL public defaults.
                If you want a custom server experience, edit or replace the files in this folder.

                Main files:

                settings.json
                - Enables/disables recipes, worldgen, structure events, strict mode and Creative Mode behavior.
                - enableStructureWorldgen controls natural structure generation in new chunks.
                - enableStructureEvents controls whether Lucky Block pool events of type structure are allowed to run.
                - strictConfigEvents prevents hidden fallback events outside the loaded config.

                tiers.json
                - Controls locked-tier level ranges used by:
                  /luckyblockgive <target> <type> <tier> [amount]

                pools/default.json
                - Controls the regular/default Lucky Block events.
                - This file uses the events array.
                - The default generated file keeps the same event types and chances from the legacy default config.

                pools/legendary.json
                - Controls the Legendary Lucky Block species, level ranges and shiny chance.

                pools/themed/*.json
                - Controls each themed Lucky Block.
                - The pokemon/pokemons list controls exactly which species can spawn.
                - The default generated files keep the same event types, species lists and chances from the legacy themed configs.

                Commands:

                /luckyblock reload
                - Reloads Lucky Block configs.
                - Requires admin/operator permission.

                /luckyblockgive <target> <type> <tier> [amount]
                - Gives locked-tier Lucky Blocks.
                - Types: default, fire, water, grass, ground, fly, steel, eletric, fairy.
                - Default aliases: default, normal, base, pocket.
                - Requires admin/operator permission.

                /luckyblocklocate [range]
                - Finds Lucky Blocks in loaded chunks.
                - Requires admin/operator permission.

                ALPHA AWAKENING (Cobblemon 1.8+):

                Event type alpha_cobblemonp (default pool and themed pools):
                - Spawns an Alpha Pokemon with a dramatic entrance, a boss bar and an optional herd.
                - Defeating the Alpha gives ONE reward (Type Gems, a TM, a Gem Block or a bonus item),
                  because Cobblemon already drops its normal loot on the ground.
                - Capturing the Alpha gives the full loot: Type Gems always, plus a TM, a Gem Block and
                  a bonus item, each rolled with its own chance.
                - Locked-tier Lucky Blocks (/luckyblockgive) NEVER run Alpha events.
                - Disable globally with enableAlphaEvents: false in settings.json.
                Main fields:
                - pokemons: species list, or randomSpecies: true (final evolutions only,
                  minBaseStatTotal filter, optional speciesTypes filter).
                - excludeLabels: species labels never picked by randomSpecies
                  (default: legendary, mythical, ultra_beast, paradox, restricted, baby; [] = allow all).
                - scaleWithParty: true = level of the strongest Pokemon in the nearest player's party
                  + partyLevelBonus (0 = same level). Without a party: pool level + levelBonus.
                - maxLevelCap, shinyChance.
                - announceRadius, bossBar, bossBarSeconds.
                - herd: { min, max, levelOffsetMin, levelOffsetMax } (followers use the Alpha's pre-evolutions).
                - rewards: { gemChance, gemMin, gemMax, gemTypes, gemBlockChance, tmChance, tmTypes, bonusItems, bonusChance }.
                  On defeat the *Chance values are weights used to pick the single reward.
                  On capture they are independent % chances (gems are always given).
                  Empty gemTypes/tmTypes use the Alpha's own types.

                Event type tm:
                - Drops random Technical Machines. tmTypes filters by type (themed pools use the block types
                  when empty, the default pool uses any type). min/max control the amount.

                legendary.json bonusDrops:
                - { enabled, chance, gemMin, gemMax, tmChance } extra Type Gems/TM of the legendary's types.
                  enabled: false turns it off; chance is the % of legendary blocks that give the bonus;
                  tmChance is the % chance of also getting a TM of the legendary's types.

                Automatic upgrades:
                - autoUpgradePools: true appends new events (marked with upgradeId) to pools that already
                  exist, only once per version. A copy named *.pre-<version>.bak is kept.

                Legacy compatibility:

                Older config files are still supported when the new files do not exist yet.
                On first load, the mod can migrate old files into the new folder.
                Once the new folder exists and has been customized, it takes priority.

                Legacy files kept for compatibility:
                - config/luckyblock_settings.json
                - config/luckyblock_locked_tiers.json
                - config/luckyblock_config.json
                - config/luckyblock_legendary.json
                - config/luckblockpocket/*.json

                Server safety:

                The mod no longer runs hidden fallback events when a pool is empty or when all chances are 0.
                If a valid event is not present in the loaded config, it will not run.
                Structure events require both:
                - an explicit structure event inside the pool
                - enableStructureEvents: true in settings.json
                """;

        try (Writer writer = new OutputStreamWriter(Files.newOutputStream(readme), StandardCharsets.UTF_8)) {
            writer.write(content);
            System.out.println("[LuckyBlockCobblemon] Generated config/luckyblockcobblemon/README.txt");
        } catch (IOException e) {
            System.out.println("[LuckyBlockCobblemon] Failed to generate config README: " + e.getMessage());
        }
    }

    private static boolean isCurrent(Path readme) {
        try {
            return Files.readString(readme, StandardCharsets.UTF_8).contains("Capturing the Alpha gives the full loot");
        } catch (IOException e) {
            return true;
        }
    }
}
